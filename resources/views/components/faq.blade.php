<script>
    document.querySelectorAll('.faq-button').forEach(button => {
        button.addEventListener('click', () => {
            const currentItem = button.parentElement;
            const answer = currentItem.querySelector('.faq-answer');
            const iconContainer = button.querySelector('.faq-icon');
            const icon = iconContainer.querySelector('i');

            // Cek apakah item ini sudah terbuka
            const isOpen = answer.style.maxHeight && answer.style.maxHeight !== '0px';

            // Tutup semua FAQ lainnya agar fokus (Optional)
            document.querySelectorAll('.faq-answer').forEach(el => el.style.maxHeight = '0px');
            document.querySelectorAll('.faq-icon').forEach(el => {
                el.classList.replace('bg-[#0064D2]', 'bg-blue-50');
                el.classList.replace('text-white', 'text-[#0064D2]');
                el.querySelector('i').classList.replace('fa-minus', 'fa-plus');
            });

            // Jika belum terbuka, maka buka
            if (!isOpen) {
                answer.style.maxHeight = answer.scrollHeight + "px";
                iconContainer.classList.replace('bg-blue-50', 'bg-[#0064D2]');
                iconContainer.classList.replace('text-[#0064D2]', 'text-white');
                icon.classList.replace('fa-plus', 'fa-minus');
            }
        });
    });
</script>
