<!-- Script untuk menggerakkan indikator dots -->
<script>
    document.addEventListener("DOMContentLoaded", function() {
        const slider = document.getElementById('program-slider');
        const dots = document.querySelectorAll('#slider-dots .dot');

        if (!slider || dots.length === 0) return;

        slider.addEventListener('scroll', () => {
            const itemWidth = slider.scrollWidth / dots.length;
            const activeIndex = Math.round(slider.scrollLeft / itemWidth);
            dots.forEach((dot, index) => {
                if (index === activeIndex) {
                    dot.className =
                        "dot w-8 h-2.5 bg-[#0064D2] rounded-full transition-all duration-300";
                } else {
                    dot.className =
                        "dot w-2.5 h-2.5 bg-blue-100 rounded-full transition-all duration-300 cursor-pointer hover:bg-blue-300";
                }
            });
        });

        dots.forEach((dot, index) => {
            dot.addEventListener('click', () => {
                const itemWidth = slider.scrollWidth / dots.length;
                slider.scrollTo({
                    left: index * itemWidth,
                    behavior: 'smooth'
                });
            });
        });
    });
</script>
