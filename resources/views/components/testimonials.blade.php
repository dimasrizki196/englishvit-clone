<script>
    document.addEventListener("DOMContentLoaded", function() {
        // Script untuk Slider Testimoni
        const testiSlider = document.getElementById('testi-slider');
        const testiDots = document.querySelectorAll('#testi-dots .testi-dot');

        if (!testiSlider || testiDots.length === 0) return;

        testiSlider.addEventListener('scroll', () => {
            const itemWidth = testiSlider.scrollWidth / testiDots.length;
            const activeIndex = Math.round(testiSlider.scrollLeft / itemWidth);

            testiDots.forEach((dot, index) => {
                if (index === activeIndex) {
                    dot.className =
                        "testi-dot w-8 h-2.5 bg-[#0064D2] rounded-full transition-all duration-300";
                } else {
                    dot.className =
                        "testi-dot w-2.5 h-2.5 bg-[#D1E4FA] rounded-full transition-all duration-300 cursor-pointer hover:bg-[#0064D2]";
                }
            });
        });

        testiDots.forEach((dot, index) => {
            dot.addEventListener('click', () => {
                const itemWidth = testiSlider.scrollWidth / testiDots.length;
                testiSlider.scrollTo({
                    left: index * itemWidth,
                    behavior: 'smooth'
                });
            });
        });
    });
</script>
