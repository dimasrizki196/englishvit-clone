<script>
    // Script untuk Slider "Why Englishvit" di Mobile
    const whySlider = document.getElementById('why-slider');
    const whyDots = document.querySelectorAll('#why-dots .why-dot');

    if (whySlider && whyDots.length > 0) {
        whySlider.addEventListener('scroll', () => {
            // Hitung lebar card untuk penentuan scroll
            const cardWidth = whySlider.scrollWidth / whyDots.length;
            const activeIndex = Math.round(whySlider.scrollLeft / cardWidth);

            whyDots.forEach((dot, index) => {
                if (index === activeIndex) {
                    dot.className =
                        "why-dot w-8 h-2 bg-[#0064D2] rounded-full transition-all duration-300";
                } else {
                    dot.className =
                        "why-dot w-2 h-2 bg-blue-100 rounded-full transition-all duration-300 cursor-pointer";
                }
            });
        });

        // Fitur klik titik untuk geser card
        whyDots.forEach((dot, index) => {
            dot.addEventListener('click', () => {
                const cardWidth = whySlider.scrollWidth / whyDots.length;
                whySlider.scrollTo({
                    left: index * cardWidth,
                    behavior: 'smooth'
                });
            });
        });
    }
</script>
